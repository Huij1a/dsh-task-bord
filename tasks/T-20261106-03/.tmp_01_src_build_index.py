def strip_label(v, label):
    v = v.strip()
    if v.startswith(label):
        v = v[len(label):]
        v = re.sub(r"^（[^）]*）", "", v)
        v = re.sub(r"^[：:为]", "", v)
    return v


def sha256_file(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def meta_of(path):
    t = open(path, encoding="utf-8").read()
    m = re.search(r"<!--(.*?)-->", t, re.S)
    block = m.group(1) if m else ""
    out = {}
    for line in block.splitlines():
        if ":" in line:
            k, v = line.split(":", 1)
            out[k.strip()] = v.strip()
    return out


